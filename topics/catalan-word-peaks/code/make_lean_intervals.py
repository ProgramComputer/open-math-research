"""Propose dyadic isolating intervals for the Lean certificate checker."""

from argparse import ArgumentParser
import json
from pathlib import Path


def sign(coefficients, numerator, denominator):
    value, power = 0, 1
    for coefficient in reversed(coefficients):
        value = coefficient * power - numerator * value
        power *= denominator
    return (value > 0) - (value < 0)


def isolate(coefficients, lower, upper, denominator, left_sign):
    if sign(coefficients, lower, denominator) != left_sign:
        raise ArithmeticError('unexpected lower endpoint sign')
    if sign(coefficients, upper, denominator) != -left_sign:
        raise ArithmeticError('unexpected upper endpoint sign')
    while upper - lower > 1:
        middle = (upper + lower) // 2
        middle_sign = sign(coefficients, middle, denominator)
        if middle_sign == 0:
            lower, upper = middle - 1, middle + 1
            if (sign(coefficients, lower, denominator) != left_sign
                    or sign(coefficients, upper, denominator) != -left_sign):
                raise ArithmeticError('grid does not isolate the exact grid root')
            break
        if middle_sign == left_sign:
            lower = middle
        else:
            upper = middle
    return lower, upper


def generate_rows(coefficients, denominator):
    previous = []
    for n, row in enumerate(coefficients):
        boxes = []
        for i in range(len(row) - 1):
            lower = previous[i - 1][1] if i else 0
            if i < len(previous):
                upper = previous[i][0]
            else:
                # Integer grid point beyond the Cauchy bound.
                upper = denominator * (max(row) // row[-1] + 2)
            try:
                boxes.append(isolate(row, lower, upper, denominator, (-1) ** i))
            except ArithmeticError as exc:
                raise ArithmeticError(f'row {n}, interval {i}: {exc}') from exc
        yield boxes
        previous = boxes


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    parser.add_argument('--bits', type=int, default=80)
    parser.add_argument('--last', type=int, default=150)
    args = parser.parse_args()
    with args.archive.open() as source:
        records = [json.loads(line) for line in source]
    records = records[:args.last + 1]
    if [record['n'] for record in records] != list(range(args.last + 1)):
        raise ValueError('archive does not cover the requested prefix')
    denominator = 2 ** args.bits
    rows = list(generate_rows((record['coefficients'] for record in records), denominator))
    print('import CatalanStrictPeaksFinite\n')
    print('/-! Dyadic interval data generated by `code/make_lean_intervals.py`. -/\n')
    print('namespace CatalanStrictPeaks.Finite\n')
    print(f'def denominator : ℕ := {denominator}\n')
    print('def prefixBoxes : Array Boxes := #[')
    for row in rows:
        intervals = [f'({lower}, {upper})' for lower, upper in row]
        lines = [', '.join(intervals[i:i + 4]) for i in range(0, len(intervals), 4)]
        formatted = ',\n    '.join(lines)
        print(f'  #[{formatted}],')
    print(']\n\nend CatalanStrictPeaks.Finite')


if __name__ == '__main__':
    main()
